#!/usr/bin/env python3
"""Write tests/TEST_PORTING.md: every Python test and the C++ test that ports it.

Each ported GoogleTest case carries one ``// py: <node id>`` comment per Python
test (or parametrised instance) it covers. This script collects the Python
node ids with pytest, scans tests/test_*.cpp for those markers and reports
which Python tests have a C++ counterpart, so nothing silently disappears.

    .venv/bin/python tools/test_porting_report.py [--check]

``--check`` exits non-zero if any Python test is unported.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TESTS = REPO / "tests"
MARKER = re.compile(r"//\s*py:\s*(\S+)")
TEST_DECL = re.compile(r"^\s*TEST(?:_F|_P)?\(\s*(\w+)\s*,\s*(\w+)\s*\)")


def python_nodes() -> list[str]:
    completed = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q", "-o", "addopts=",
         "-p", "no:cacheprovider", str(TESTS)],
        cwd=REPO, capture_output=True, text=True,
    )
    nodes = [line.strip() for line in completed.stdout.splitlines() if "::" in line]
    return [n[len("tests/"):] if n.startswith("tests/") else n for n in nodes]


def cpp_markers() -> dict[str, list[str]]:
    """node id -> ['test_x.cpp: Suite.Name', ...]"""
    found: dict[str, list[str]] = defaultdict(list)
    for source in sorted(TESTS.glob("test_*.cpp")):
        pending: list[str] = []
        for line in source.read_text(encoding="utf-8").splitlines():
            marker = MARKER.search(line)
            if marker:
                pending.append(marker.group(1))
                continue
            decl = TEST_DECL.match(line)
            if decl and pending:
                for node in pending:
                    found[node].append(f"{source.name}: {decl.group(1)}.{decl.group(2)}")
                pending = []
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    nodes = python_nodes()
    markers = cpp_markers()
    unknown = sorted(set(markers) - set(nodes))

    by_module: dict[str, list[str]] = defaultdict(list)
    for node in nodes:
        by_module[node.split("::", 1)[0]].append(node)

    ported = sum(1 for n in nodes if n in markers)
    lines = [
        "# Python -> C++ test porting checklist",
        "",
        "Generated by `tools/test_porting_report.py`; do not edit by hand.",
        "",
        f"**{ported} of {len(nodes)}** collected Python tests (parametrised instances counted",
        "individually) have a C++ counterpart, identified by a `// py: <node id>` marker on",
        "the GoogleTest case.",
        "",
        "| Python module | Python tests | Ported |",
        "|---|---:|---:|",
    ]
    for module, module_nodes in sorted(by_module.items()):
        count = sum(1 for n in module_nodes if n in markers)
        lines.append(f"| `{module}` | {len(module_nodes)} | {count} |")
    lines.append("")
    for module, module_nodes in sorted(by_module.items()):
        lines += [f"## {module}", ""]
        for node in module_nodes:
            target = "; ".join(markers.get(node, [])) or "**not ported**"
            lines.append(f"- [{'x' if node in markers else ' '}] `{node.split('::', 1)[1]}` -> {target}")
        lines.append("")
    if unknown:
        lines += ["## Markers that match no Python test", ""]
        lines += [f"- `{node}`" for node in unknown]
        lines.append("")

    (TESTS / "TEST_PORTING.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"{ported}/{len(nodes)} Python tests ported; wrote tests/TEST_PORTING.md")
    if unknown:
        print(f"warning: {len(unknown)} markers match no Python test: {unknown[:5]}")
    if args.check and (ported != len(nodes) or unknown):
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
